// Client-side CSV and PDF export.
// columns: [{ label, value: (row) => displayValue, csv?: (row) => rawValue, align?: "right" }]

const triggerDownload = (blob, filename) => {
  const url = URL.createObjectURL(blob);
  const link = Object.assign(document.createElement("a"), { href: url, download: filename });
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
};

const csvCell = (value) => {
  const text = String(value ?? "");
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

export const downloadCSV = (filename, columns, rows) => {
  const lines = [
    columns.map((c) => csvCell(c.label)).join(","),
    ...rows.map((row) => columns.map((c) => csvCell(c.csv ? c.csv(row) : c.value(row))).join(",")),
  ];
  // The BOM makes Excel open the file as UTF-8 (so ₹ and other symbols display correctly).
  triggerDownload(new Blob(["﻿" + lines.join("\r\n")], { type: "text/csv;charset=utf-8" }), filename);
};

export const downloadPDF = async (filename, { title, subtitle, columns, rows, footer }) => {
  // Loaded on demand so the PDF library isn't part of the main bundle.
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);
  const doc = new jsPDF({ orientation: columns.length > 5 ? "landscape" : "portrait" });

  doc.setFontSize(16);
  doc.text(title, 14, 18);
  doc.setFontSize(10);
  doc.setTextColor(110);
  doc.text(subtitle, 14, 25);

  const rightAligned = Object.fromEntries(
    columns.map((c, i) => [i, c.align === "right" ? { halign: "right" } : {}])
  );
  autoTable(doc, {
    startY: 31,
    head: [columns.map((c) => c.label)],
    body: rows.map((row) => columns.map((c) => c.value(row))),
    foot: footer ? [footer] : undefined,
    styles: { fontSize: 9, cellPadding: 2.5 },
    headStyles: { fillColor: [42, 120, 214] },
    footStyles: { fillColor: [240, 239, 236], textColor: 20, fontStyle: "bold" },
    columnStyles: rightAligned,
    didDrawPage: () => {
      doc.setFontSize(8);
      doc.setTextColor(150);
      doc.text(`Generated by SubTrack on ${new Date().toLocaleString("en-IN")}`, 14, doc.internal.pageSize.getHeight() - 8);
    },
  });
  doc.save(filename);
};

export const fileStamp = () => new Date().toISOString().slice(0, 10);
